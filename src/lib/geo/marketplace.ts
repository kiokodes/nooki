/**
 * The marketplace seam: which city the shop opens on.
 *
 * Nothing here sells anything yet, and deliberately so — there are no vendor tables, no
 * listings and no Market tab. What exists is the one decision the whole feature rests on,
 * written down and tested before any of it is built:
 *
 *   Gifting somebody far away is hard because you do not know anywhere in *their* city.
 *   So Nooki's marketplace opens on the partner's city, not yours, and offers the others
 *   you have saved as a switcher — for the week they are on holiday somewhere else, or
 *   for the city they grew up in and still want to send things to.
 *
 * When the vendor platform lands it takes `defaultCity.key` (`ng/ri/port-harcourt`) as the
 * scope for its first query and `cities` as the switcher, and nothing about the location
 * model has to change. That key is generated by the database on `profiles.city_key`.
 */
import type { Profile } from '../../types/database';
import { buildCityKey, describePlace, describePlaceShort } from './location';

/** One city the marketplace can be pointed at. */
export interface MarketCity {
  /** `ng/ri/port-harcourt` — the scope a vendor query will be filtered by. */
  key: string;
  /** "Port Harcourt, Rivers, Nigeria", ready to render as a heading. */
  name: string;
  /** "Port Harcourt, NG" — the same city as a switcher chip. */
  shortName: string;
  cityName: string;
  stateName: string | null;
  countryCode: string;
  countryName: string;
  /** That city's zone, so a gift can be timed for the person receiving it. */
  timezone: string | null;
  /** Whose city it is. The marketplace opens on 'partner', because the gift goes to them. */
  belongsTo: 'partner' | 'you';
}

export interface MarketContext {
  /** True once there is a city to open on — which means the partner has saved one. */
  ready: boolean;
  /** The city the marketplace opens on; null while the partner has no location. */
  defaultCity: MarketCity | null;
  /** Every city on offer, the partner's first and yours next when it is somewhere else. */
  cities: MarketCity[];
  /** What to say when it is not ready, in a sentence worth showing on a phone. */
  notice: string | null;
}

/**
 * A profile as a city, or null when that person has not saved a location yet.
 *
 * The database generates `city_key`; recomputing it here only covers a row read from a
 * project that has the columns but not the generated one, and the two are asserted equal
 * in `tests/location-database.test.mjs`.
 */
export function marketCityFromProfile(profile: Profile | null, belongsTo: MarketCity['belongsTo']): MarketCity | null {
  if (!profile?.city_name || !profile.country_code) return null;
  const key = profile.city_key || buildCityKey({
    countryCode: profile.country_code,
    stateCode: profile.state_code,
    cityName: profile.city_name,
  });
  if (!key) return null;
  return {
    key,
    name: describePlace({
      cityName: profile.city_name,
      stateName: profile.state_name,
      countryName: profile.country_name,
    }),
    shortName: describePlaceShort({
      cityName: profile.city_name,
      countryCode: profile.country_code,
      countryName: profile.country_name,
    }),
    cityName: profile.city_name,
    stateName: profile.state_name,
    countryCode: profile.country_code,
    countryName: profile.country_name ?? '',
    timezone: profile.timezone || null,
    belongsTo,
  };
}

/**
 * The cities this couple's marketplace has to work with.
 *
 * Order is the point: the partner's city first, because that is where the gift is going,
 * then your own when it is somewhere else — which is the "other cities" switcher, and the
 * reason a couple who have moved to the same country (same zone, different city) still
 * gets something useful out of Nooki.
 */
export function resolveMarketCities(profile: Profile | null, partner: Profile | null): MarketContext {
  const partnerCity = marketCityFromProfile(partner, 'partner');
  const ownCity = marketCityFromProfile(profile, 'you');
  const cities = [partnerCity, ownCity].filter(
    (city, index, all): city is MarketCity => city !== null && all.findIndex((other) => other?.key === city.key) === index,
  );

  if (!partnerCity) {
    const partnerName = partner?.name?.trim() || 'Your partner';
    return {
      ready: false,
      defaultCity: null,
      cities,
      notice: `${partnerName} has not added their city yet. The marketplace opens on where they are, so ask them to add it in Couple Settings.`,
    };
  }
  return { ready: true, defaultCity: partnerCity, cities, notice: null };
}
